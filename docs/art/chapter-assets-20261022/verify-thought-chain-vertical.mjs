import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';

const root = process.cwd();
const dir = path.join(root, 'source-art/visuals/investigation-expansion-20261022');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const result = { checkedAt: new Date().toISOString(), browser: 'msedge headless', devices: [] };
const pause = page => page.waitForTimeout(650);
try {
  for (const mobile of [false, true]) {
    const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, isMobile: mobile, hasTouch: mobile, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const name = mobile ? 'mobile' : 'desktop';
    const activate = async locator => mobile ? locator.tap() : locator.click();
    await page.goto(pathToFileURL(path.join(dir, 'thought-chain-vertical.html')).href);
    await page.evaluate(() => sessionStorage.clear());
    await page.reload();
    await page.locator('.ink-scroll').evaluate(async img => { if (!img.complete) await new Promise(resolve => { img.onload = resolve; img.onerror = resolve; }); });
    assert.equal(await page.locator('.proofs').count(), 0, `${name}: proof area before choice`);
    assert.equal(await page.locator('.step').count(), 1);
    assert.equal(await page.locator('#motion').textContent(), '动效 关');
    assert.equal(await page.locator('.ink-scroll').evaluate(el => getComputedStyle(el).animationName), 'none');
    await activate(page.locator('[data-step="0"][data-choice="0"]'));
    assert.equal(await page.locator('#step-0 .proofs').count(), 1);
    assert.equal(await page.locator('#step-0 .slip').count(), 0, `${name}: auto placed evidence`);
    assert(await page.locator('[data-save="0"]').isDisabled());
    await activate(page.locator('[data-picker="0"]'));
    assert.equal(await page.locator('#step-0 .pickrow').count(), 3);
    await activate(page.locator('#step-0 .picker [data-read="receipt"]'));
    assert(await page.locator('#detail').isVisible());
    assert.match(await page.locator('#detail').textContent(), /实际签收/);
    const detailRect = await page.locator('#detail').boundingBox();
    assert(detailRect.x >= 0 && detailRect.x + detailRect.width <= (mobile ? 390 : 1440));
    await activate(page.locator('#close-detail'));
    await activate(page.locator('#step-0 [data-put="receipt"]'));
    assert.equal(await page.locator('#step-0 .slip').count(), 1);
    assert(await page.locator('[data-save="0"]').isEnabled());
    if (mobile) await page.locator('#step-0').evaluate(el => el.scrollIntoView({block:'start'}));
    else await page.locator('#scroll').evaluate(el => el.scrollTo(0, 0));
    await page.screenshot({ path: path.join(dir, `proof-vertical-${name}.png`) });
    await activate(page.locator('[data-save="0"]'));
    await pause(page);
    assert.equal(await page.locator('.step').count(), 2);
    assert.equal(await page.locator('#step-0 .slip').count(), 1);
    assert.equal(await page.locator('#step-0 .summary').count(), 1);
    const y0 = await page.locator('#step-0').evaluate(el => el.offsetTop);
    const y1 = await page.locator('#step-1').evaluate(el => el.offsetTop);
    assert(y1 > y0, `${name}: next stage is not below predecessor`);
    assert.equal(await page.locator('#step-1 .proofs').count(), 0);
    for (let i=1; i<4; i++) {
      await activate(page.locator(`[data-step="${i}"][data-choice="0"]`));
      assert.equal(await page.locator(`#step-${i} .slip`).count(), 0);
      await activate(page.locator(`[data-picker="${i}"]`));
      await activate(page.locator(`#step-${i} [data-put]`).first());
      await activate(page.locator(`[data-save="${i}"]`));
      await pause(page);
    }
    assert.equal(await page.locator('.step').count(), 4);
    assert.equal(await page.locator('.summary').count(), 4);
    assert(await page.locator('#journey-end').isVisible());
    await page.reload();
    await pause(page);
    assert.equal(await page.locator('.summary').count(), 4, `${name}: refresh lost saved history`);
    assert.equal(await page.locator('.slip').count(), 4, `${name}: refresh lost evidence`);
    const latestRect = await page.locator('#step-3 h2').boundingBox();
    const scrollRect = await page.locator('#scroll').boundingBox();
    assert(latestRect.y >= scrollRect.y && latestRect.y + latestRect.height <= scrollRect.y + scrollRect.height, `${name}: latest question not visible after refresh`);
    await page.locator('#step-0').evaluate(el => el.scrollIntoView({block:'start'}));
    await pause(page);
    const oldTop = await page.locator('#scroll').evaluate(el => el.scrollTop);
    await activate(page.locator('#step-0 .slip [data-read]'));
    assert(await page.locator('#detail').isVisible());
    const detailTop = await page.locator('#scroll').evaluate(el => el.scrollTop);
    assert(Math.abs(detailTop-oldTop)<2, `${name}: detail jumps scroll to latest ${oldTop} -> ${detailTop}`);
    await activate(page.locator('#close-detail'));
    await activate(page.locator('[data-revise="0"]'));
    const reviseTop = await page.locator('#scroll').evaluate(el => el.scrollTop);
    assert(Math.abs(reviseTop-oldTop)<2, `${name}: revise jumps scroll ${oldTop} -> ${reviseTop}`);
    assert.equal(await page.locator('.step').count(), 4, `${name}: history lost`);
    await activate(page.locator('[data-step="0"][data-choice="1"]'));
    assert.equal(await page.locator('#step-0 .slip').count(), 0, `${name}: revised choice inherits automatic proof`);
    assert(await page.locator('[data-save="0"]').isDisabled());
    const layout = await page.evaluate(() => ({ width: innerWidth, docWidth: document.documentElement.scrollWidth, scrollWidth: document.querySelector('#scroll').scrollWidth, clientWidth: document.querySelector('#scroll').clientWidth, touchTargets: [...document.querySelectorAll('button')].filter(el => el.getBoundingClientRect().height).map(el => ({ label: el.textContent, width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height })) }));
    assert(layout.docWidth <= layout.width, `${name}: document overflow`);
    assert(layout.scrollWidth <= layout.clientWidth, `${name}: canvas overflow`);
    assert(layout.touchTargets.every(t => t.height >= 44), `${name}: undersized vertical touch targets`);
    assert.deepEqual(errors, []);
    result.devices.push({ name, viewport: mobile ? '390x844' : '1440x1000', checks: 'All interaction, vertical progression, history, refresh restoration and latest positioning, scroll stability, overflow, touch interaction, and reduced-motion assertions passed', screenshot: path.join(dir, `proof-vertical-${name}.png`), layout, errors });
    await context.close();
  }
} finally { await browser.close(); }
await fs.writeFile(path.join(root, 'docs/art/chapter-assets-20261022/vertical-review-results.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
