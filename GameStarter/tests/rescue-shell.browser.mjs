import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createStaticServer } from '../web-demo/serve.mjs';

const directory = await mkdtemp(join(tmpdir(), 'eight-rescue-shell-'));
const server = createStaticServer({ commandOptions: {directory, reportModel:false, eventModel:false, model:async()=>{throw Error('Unexpected model request');}} });
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin = 'http://127.0.0.1:' + server.address().port;
const browser = await chromium.launch({channel:'chrome',headless:true});
const key = 'yiling-command-chapter-v1';
try {
    const page = await browser.newPage({viewport:{width:1440,height:900}});
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    const requestSession = async (scenarioId) => (await (await page.request.post(origin+'/api/yiling-command/session', {data:{scenarioId}})).json()).session;
    const former = await requestSession();
    await page.addInitScript(id=>{
        localStorage.setItem('yiling-shared-campaign-v1',JSON.stringify({id,history:[id]}));
        localStorage.setItem('yiling-rescue-campaign-session-v1','legacy-nine');
    },former.scenarioId);
    await page.route('**/api/game/settings',route=>route.fulfill({json:{apiKey:'',model:'',baseUrl:''}}));
    await page.route('**/api/yiling-command/chat',route=>route.fulfill({status:400,json:{error:'本机尚未配置AI。'}}));
    await page.goto(origin+'/?chapter=yiling&playtest=reception');
    await page.locator('[data-cinema-action=skip]').click();
    const frame=page.frameLocator('iframe');
    const currentId = ()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)).id,key);
    const pause = ()=>frame.locator('#campaign-pause').click();
    const saveMenu = async()=>{await pause();await page.locator('[data-action=pause-save]').click();};
    const closeSave = async()=>{await page.locator('[data-action=close-modal]').click();await page.locator('[data-action=resume-game]').click();};
    await frame.locator('#places [data-front=fu]').click();
    await frame.locator('#story-talk').click();
    assert.equal(await currentId(),former.scenarioId);
    assert.equal(await page.evaluate(()=>localStorage.getItem('yiling-rescue-campaign-session-v1')),'legacy-nine');

    await frame.locator('#draft').fill('营里有消息吗？');
    await frame.locator('#send').click();
    await frame.locator('#configure-ai').click();
    await page.locator('.ai-setup-dialog').waitFor();
    await page.locator('[data-setup-close]').click();
    assert.equal(await frame.locator('#draft').inputValue(),'营里有消息吗？');

    await frame.locator('#mode-toggle').click();
    await frame.locator('#draft').fill('派300人接应沙摩柯');
    await frame.locator('#send').click();
    await frame.locator('#preview').waitFor();
    await frame.locator('#send').click();
    await frame.locator('#preview').waitFor({state:'hidden'});
    assert.equal(await frame.locator('#order-pace').count(),0);
    await frame.locator('#draft').fill('尚未发送的军令草稿');
    const queued=await requestSession(former.scenarioId);
    assert.equal(queued.reserve,1700);
    assert.equal(queued.round,0);
    await saveMenu();
    await page.locator('[data-store-slot="1"]').click();
    await page.getByRole('status').filter({hasText:'进度已保存'}).waitFor();
    const slot=await page.evaluate(key=>JSON.parse(localStorage.getItem(key+':manual:1')),key);
    assert.equal(slot.round,1);
    assert.equal(Object.hasOwn(slot,'rush'),false);
    assert.deepEqual(slot.visitedFronts,['fu']);
    await closeSave();
    await frame.locator('.army-camp.unread').click();
    await frame.locator('#close-story').click();
    assert.equal(await frame.locator('#contacts button').count(),2);
    await frame.locator('#mode-toggle').click();
    await frame.locator('#fu-end-round').click();
    await frame.locator('#advance-without-order').click();
    await frame.locator('#round-report[open] form button').click();
    assert.equal((await requestSession(former.scenarioId)).round,1);
    await saveMenu();
    await page.locator('[data-load-slot="1"]').click();
    await page.waitForFunction(({key,id})=>JSON.parse(localStorage.getItem(key)).id!==id,{key,id:former.scenarioId});
    await frame.locator('.roster-row').first().waitFor();
    const restoredId=await currentId(),restored=await requestSession(restoredId);
    assert.equal(restored.round,0);
    await frame.locator('.army-camp.unread').waitFor();
    await frame.locator('#contacts button[data-front=fu]').waitFor();
    assert.deepEqual(await frame.locator('#contacts button').evaluateAll(buttons=>buttons.map(b=>b.dataset.front)),['fu']);
    assert.equal(await frame.locator('.front-alert').count(),2);
    assert.equal(restored.reserve,queued.reserve);
    assert.deepEqual(restored.units,queued.units);
    assert.equal(await frame.locator('#draft').inputValue(),'尚未发送的军令草稿');
    assert.equal(await frame.locator('#order-pace').count(),0);
    assert.equal((await requestSession(former.scenarioId)).round,1);
    assert.equal(await page.evaluate(key=>JSON.parse(localStorage.getItem(key+':manual:1')).id,key),slot.id);

    await pause();
    await page.locator('[data-action=settings]').click();
    await page.locator('#game-ai-enabled').waitFor();
    await page.locator('[data-action=close-modal]').click();
    await page.locator('[data-action=pause-restart]').click();
    await frame.locator('#cancel-reset').click();
    assert.equal(await currentId(),restoredId);
    await pause();
    await page.locator('[data-action=pause-restart]').click();
    await frame.locator('#confirm-reset').click();
    await page.waitForFunction(({key,id})=>JSON.parse(localStorage.getItem(key)).id!==id,{key,id:restoredId});
    const replay=await currentId();
    assert.equal((await requestSession(replay)).reserve,2000);
    await frame.locator('#campaign-map').click();
    await page.locator('[data-map-node=yiling] a').click();
    await frame.locator('.map-first .army-fu.unread').waitFor();
    assert.equal(await currentId(),replay);
    for(const path of ['/?chapter=yiling&playtest=command','/?chapter=yiling&playtest=story','/yiling-rescue/index.html','/chapter-result-import.html']){
        await page.goto(origin+path);
        await frame.locator('.map-first .army-fu.unread').waitFor();
        assert.equal(await currentId(),replay);
        assert.match(await page.locator('iframe').getAttribute('src'), /yiling-command.*chapter=yiling/);
    }
    assert.equal((await page.request.get(origin+'/api/yiling-rescue/health')).status(),404);
    assert.equal(await page.evaluate(()=>localStorage.getItem('yiling-rescue-campaign-session-v1')),'legacy-nine');
    assert.deepEqual(errors,[]);
    console.log('PASS formal eight-route entry, legacy links, verified v4 resume, AI setup, queued orders, draft, immutable slot, restore, restart, map and re-entry.');
} finally {
    await browser.close();
    server.closeAllConnections();
    await new Promise(resolve=>server.close(resolve));
    await rm(directory,{recursive:true,force:true});
}
