import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { mkdtemp, rm, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { createStaticServer } from '../web-demo/serve.mjs';
const saves = await mkdtemp(resolve(tmpdir(), 'rescue-shell-'));
const server = createStaticServer({rescueOptions:{saveDir:saves,ai:async()=>{throw new Error('No live AI in this test');}}});
await new Promise(done=>server.listen(0,'127.0.0.1',done));
const origin=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:900}});page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/api/game/settings',route=>route.fulfill({json:{apiKey:'',model:'',baseUrl:''}}));
 await page.goto(origin+'/?chapter=yiling');
 await page.locator('[data-cinema-action=skip]').click();
 const frame=page.frameLocator('iframe');
 await frame.locator('[data-action=start]').click();
 await frame.locator('.campaign-header').waitFor();
 const key='yiling-rescue-campaign-session-v1';
 const first=await page.evaluate(key=>localStorage.getItem(key),key);
 await frame.locator('[data-action=campaign-pause]').click();
 await page.locator('[data-action=pause-save]').click();
 await page.locator('[data-store-slot="1"]').click();
 await page.getByRole('status').filter({hasText:'进度已保存'}).waitFor();
 const slot=await page.evaluate(key=>JSON.parse(localStorage.getItem(key+':manual:1')),key);
 assert.equal(slot.version,1);assert.equal(slot.round,1);
 await page.locator('[data-action=close-modal]').click();
 await page.locator('[data-action=resume-game]').click();
 await frame.locator('[data-target=liu]').click();
 await frame.locator('[data-action=camp-advance]').click();
 await frame.locator('[data-camp-route=front]').click();
 await frame.locator('[data-action=close-sheet]').click();
 await frame.locator('[data-action=campaign-pause]').click();
 await page.locator('[data-action=pause-save]').click();
 await page.locator('[data-load-slot="1"]').click();
 await page.waitForFunction(({key,first})=>localStorage.getItem(key)!==first,{key,first});
 await frame.locator('.campaign-header').waitFor();
 const second=await page.evaluate(key=>localStorage.getItem(key),key);
 const state=await(await page.request.get(origin+'/api/yiling-rescue/state?session='+second)).json();
 assert.equal(state.state.routes.some(route=>route.id==='front'),false);
 assert.equal(await page.evaluate(key=>localStorage.getItem(key+':before-new'),key),first);
 assert.equal(await page.evaluate(key=>JSON.parse(localStorage.getItem(key+':manual:1')).id,key),slot.id);
 await frame.locator('[data-action=campaign-pause]').click();
 await page.locator('[data-action=settings]').click();
 await page.locator('#ai-voice-enabled').waitFor();
 const voice=page.locator('#ai-voice-enabled');
 if(await voice.isEnabled()){await voice.setChecked(false);assert.equal(await voice.isChecked(),false);}
 await page.locator('[data-action=close-modal]').click();
 await page.locator('[data-action=pause-restart]').click();
 await page.locator('[data-action=pause-restart-confirm]').click();
 await page.waitForFunction(({key,second})=>localStorage.getItem(key)!==second,{key,second});
 await frame.locator('.campaign-header').waitFor();
 assert.equal(await page.evaluate(key=>localStorage.getItem(key+':before-new'),key),second);
 await frame.locator('[data-action=campaign-pause]').click();
 await mkdir(resolve('outputs/rescue-shell-20261117'),{recursive:true});
 await page.screenshot({path:resolve('outputs/rescue-shell-20261117/pause.png')});
 assert.deepEqual(errors,[]);
 await writeFile(resolve('outputs/rescue-shell-20261117/result.json'),JSON.stringify({passed:true,checks:['common pause','manual save','restore factual state','immutable slot','backup prior progress','optional voice control','shared restart'],errors},null,2));
 console.log('Rescue shell browser checks passed');
} finally {await browser.close();await new Promise(done=>server.close(done));await rm(saves,{recursive:true,force:true});}
