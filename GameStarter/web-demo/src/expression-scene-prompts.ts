import type { ExpressionBrief } from './expression-contract';

export function expressionLengthBudget(brief: ExpressionBrief) {
    const count = brief.selectedEvidence.length + (brief.attachedItems?.length ?? 0);
    return brief.conversation.stage === 'first'
        ? { target: count > 3 ? '60—110' : '40—85', maximum: Math.min(220, 110 + Math.max(0, count - 2) * 25) }
        : { target: count > 4 ? '115—140' : count <= 2 ? '40—80' : brief.attachedItems?.length ? '100—130' : '90—105', maximum: Math.min(240, 100 + Math.max(0, brief.selectedEvidence.length - 2) * 15 + ((brief.attachedItems?.length ?? 0) ? 30 + Math.max(0, (brief.attachedItems?.length ?? 0) - 1) * 20 : 0)) };
}

