import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync } from 'node:fs';
import { ChapterSession } from '../../GameStarter/web-demo/.build/GameStarter/web-demo/src/chapter-session.js';
const read = p => JSON.parse(readFileSync(p, 'utf8'));
const fixture = read('GameStarter/web-demo/.build/playtest/weiyan-second.json');
const session = new ChapterSession(read('content/chapters/wuzhang/chapter-one.script.json'), read('content/chapters/wuzhang/chapter-one.flow.json'), fixture.contentVersion);
fixture.supplies = { version: 1, rewards: ['R01', 'R02'], purchases: ['flashlight', 'batteries'], attached: [], agreement: null };
session.restore(JSON.stringify(fixture));
const saved = session.serialize(), key = 'wuzhang-chapter-session-v1', output = 'outputs/expression-items-20261024';
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
try {
    for (const width of [1366, 1280]) {
        const context = await browser.newContext({ viewport: { width, height: width === 1366 ? 768 : 720 }, reducedMotion: 'reduce' });
        await context.addInitScript(({ key, saved }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, saved); localStorage.setItem('wuzhang-voice-muted', '1'); }, { key, saved });
        const page = await context.newPage(), errors = []; page.on('pageerror', e => errors.push(e.message));
        const state = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
        await page.goto('http://127.0.0.1:8812/'); await page.locator('[data-action=continue]').click();
        assert.equal(await page.getByRole('button', { name: '＋ 添加线索', exact: true }).count(), 1);
        assert.equal(await page.getByRole('button', { name: '＋ 添加物品', exact: true }).count(), 1);
        const text = await page.locator('.expression-paper').innerText();
        assert.doesNotMatch(text, /这次依据|物品佐证|打开手机|先前保留|可附上|在“准备说的话”/);
        const sizes = await page.locator('.speech-add,.speech-add-item,#expression-focus').evaluateAll(nodes => nodes.map(e => getComputedStyle(e).fontSize));
        assert.ok(sizes.every(s => s === '16px'), JSON.stringify(sizes));
        assert.equal(await page.locator('#expression-focus').getAttribute('type'), 'text');
        assert.equal(await page.locator('#expression-focus').getAttribute('placeholder'), '补充说明…');
        assert.ok((await page.locator('#expression-focus').boundingBox()).height <= 36);
        const clueBox = await page.locator('.speech-add').boundingBox(), itemBox = await page.locator('.speech-add-item').boundingBox();
        assert.ok(itemBox.y > clueBox.y + clueBox.height); assert.ok(Math.abs(itemBox.x - clueBox.x) < 2);
        await page.screenshot({ path: `${output}/clean-${width}.png` });
        await page.locator('.speech-add').click(); await page.locator('.thought-inventory').waitFor();
        const choice = page.locator('.thought-inventory [data-place-evidence]').first(); await choice.click();
        assert.equal((await state()).story.selected.length, 1);
        await page.locator('.speech-add-item').click();
        assert.equal(await page.locator('.phone-panel').count(), 0);
        assert.equal(await page.locator('.game-modal[data-page=items]').count(), 0);
        assert.equal(await page.locator('.expression-inspection-slot .thought-inventory').count(), 1);
        assert.equal(await page.locator('[aria-label=搜索物品]').count(), 1);
        assert.equal(await page.locator('.thought-inventory .inventory-entry').count(), 2);
        assert.equal(await page.locator('[data-buy-offer],#shopping-query').count(), 0);
        await page.locator('[data-inventory-item="item:flashlight"]').click();
        assert.match(await page.locator('.thought-detail-popover').innerText(), /购入价|光不能/);
        await page.locator('.thought-inventory [data-attach-item=flashlight]').click(); await page.locator('.thought-inventory [data-attach-item=batteries]').click();
        assert.deepEqual((await state()).supplies.attached, ['flashlight', 'batteries']);
        await page.screenshot({ path: `${output}/inventory-${width}.png` });
        await page.getByRole('button', { name: '收起线索物品栏', exact: true }).click();
        assert.equal(await page.locator('.speech-items [data-attach-item]').count(), 2);
        await page.locator('.speech-items [data-attach-item=batteries]').click();
        assert.deepEqual((await state()).supplies.attached, ['flashlight']);
        await page.locator('#player-expression').fill('请看这盏灯。');
        await page.reload(); await page.locator('[data-action=continue]').click();
        assert.equal(await page.locator('#player-expression').inputValue(), '请看这盏灯。');
        assert.deepEqual((await state()).supplies.attached, ['flashlight']);
        assert.equal((await state()).story.selected.length, 1);
        assert.deepEqual(errors, []); await context.close();
    }
    console.log('Passed: compact matching add rows, single-line supplement, shared inline owned-item inventory and distinct preview, clue selection, item add/remove, draft and selections after reload; 1366 and 1280 widths.');
} finally { await browser.close(); }
