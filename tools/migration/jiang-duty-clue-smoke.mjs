import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const output = resolve('outputs/jiang-duty-clue-20261026');
mkdirSync(output, { recursive:true });
const browser = await chromium.launch({headless:true, channel:'chrome'});
const errors = [];
try {
  const context = await browser.newContext({viewport:{width:1440,height:900}, reducedMotion:'reduce'});
  await context.route('http://127.0.0.1:8787/**', route=>route.fulfill({headers:{'Access-Control-Allow-Origin':'*'},json:{configured:false}}));
  const page = await context.newPage(); page.on('pageerror', e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8812/?playtest=thoughts');
  await page.locator('[data-action=think]').click();
  await page.locator('[data-action=continue-thought]').click();
  await page.locator('[data-action=open-inventory]').click();
  await page.locator('[data-inventory-item=C07]').click();
  await page.getByText('入夜前，丞相吩咐过，今夜军务由他接报处置。', {exact:false}).first().waitFor();
  await page.locator('[data-place-evidence=C06]').click();
  await page.keyboard.press('Escape');
  if (await page.locator('#thought-inventory').count()) await page.locator('[data-action=notes-list]').last().click();
  await page.locator('[data-action=think]').click();
  assert.equal(await page.locator('[data-thought-result=R02]').count(),0);
  await page.locator('[data-action=open-inventory]').click();
  await page.locator('[data-place-evidence=C07]').click();
  await page.locator('[data-action=think]').click();
  const result = page.locator('[data-question-stage=recipient].thought-record');
  await result.waitFor();
  assert.equal(await result.locator('[data-thought-node=C06]').count(),1);
  assert.equal(await result.locator('[data-thought-node=C07]').count(),1);
  await page.locator('[data-action=follow-plan]').waitFor();
  await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:resolve(output,'two-evidence-result.png')});
  await page.goto('http://127.0.0.1:8812/?playtest=weiyan-second');
  await page.locator('[data-action=clue-items]').click();
  assert.equal(await page.locator('[data-inventory-item=R02]').count(),0);
  assert.equal(await page.locator('[data-inventory-item=C07]').count(),1);
  await page.screenshot({path:resolve(output,'clue-list.png')});
  assert.deepEqual(errors,[]);
  console.log('Browser passed: source dialogue, missing evidence rejected, two required cards displayed, plan absent from clue picker.');
} finally {await browser.close();}
