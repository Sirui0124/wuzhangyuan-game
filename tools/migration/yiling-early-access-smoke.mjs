import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createStaticServer } from '../../GameStarter/web-demo/serve.mjs';

const out = resolve('outputs/yiling-early-access-20261029');
mkdirSync(out, { recursive: true });
const ai = async (kind, input) => {
  if (kind === 'assess') return { orders: input.orders.map(o => ({ id: o.id, evidence: [], reason: '按现有军令接应。' })) };
  if (kind === 'report') return { text: '各路信使已回营。', messages: input.changes.map(c => ({ id: c.id, message: c.outcome || '仍需安排下一轮接应。' })) };
  throw new Error('此测试不调用真实模型');
};
const server = createStaticServer({ rescueOptions: { ai, saveDir: resolve(out, 'test-saves') } });
await new Promise(r => server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [], checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  await context.addInitScript(() => localStorage.setItem('wuzhang-runtime-mode-v1', 'offline'));
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  page.setDefaultTimeout(15000);
  const map = async () => { await page.goto(base + '/?view=chapters'); await page.locator('.chapter-map').waitFor(); };
  const locked = async ids => { for (const id of ids) assert.equal(await page.locator(`[data-map-node=${id}]`).evaluate(e => e.classList.contains('locked')), true, id); };
  const advance = async id => page.evaluate(async id => {
    const { recordChapterHistory } = await import('/GameStarter/web-demo/src/chapters/progression.js');
    recordChapterHistory(id, true);
  }, id);
  await map();
  await locked(['grain', 'jieting', 'jingzhou', 'luofengpo']);
  assert.equal(await page.locator('[data-map-node=yiling] .map-early-access').innerText(), '抢先体验');
  assert.equal(await page.locator('[data-map-node=yiling] a').innerText(), '开始这一章');
  for (const [width, height] of [[1440, 900], [390, 844]]) {
    await page.setViewportSize({ width, height });
    const heading = page.locator('[data-map-node=yiling] h2');
    const badge = page.locator('[data-map-node=yiling] .map-early-access');
    await badge.scrollIntoViewIfNeeded();
    const h = await heading.boundingBox(), b = await badge.boundingBox();
    assert.ok(b.x >= h.x + h.width && b.y < h.y + h.height, 'small label sits beside the title');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: resolve(out, `map-${width}.png`), fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('[data-map-node=yiling] a').click();
  let frame = page.frameLocator('iframe');
  await frame.locator('[data-action=start]').click();
  await frame.locator('.campaign-header').waitFor();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('wuzhang-chapter-history-v1')).earlyYiling === true);
  const session = await page.evaluate(() => localStorage.getItem('yiling-rescue-campaign-session-v1'));
  await frame.locator('[data-action=campaign-map]').click();
  await page.locator('.chapter-map').waitFor();
  await locked(['grain', 'jieting', 'jingzhou', 'luofengpo']);
  assert.equal(await page.locator('[data-map-node=yiling] a').innerText(), '继续这一章');
  await page.locator('[data-map-node=yiling] a').click();
  await page.reload(); frame = page.frameLocator('iframe');
  await frame.locator('.campaign-header').waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem('yiling-rescue-campaign-session-v1')), session);
  checks.push('fresh map offers Yiling only as an exception; desktop/mobile label sits beside title; returning and refreshing preserves the same session');
  for (let round = 1; round <= 6; round++) {
    await frame.locator('[data-screen=map]').first().click();
    await frame.locator('[data-action=preview]').click();
    await frame.locator('[data-action=commit]').click();
    await frame.locator('#scene-dialog [data-action=next]').click();
  }
  await frame.locator('.ending').waitFor();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('wuzhang-chapter-history-v1')).completed.includes('yiling'));
  assert.equal(await frame.locator('[data-action=campaign-next]').count(), 0);
  const result = await page.evaluate(() => JSON.parse(localStorage.getItem('wzy:chapter-results:v1')).yiling);
  await frame.locator('.ending [data-action=campaign-map]').click();
  await page.locator('.chapter-map').waitFor();
  await locked(['grain', 'jieting', 'jingzhou', 'luofengpo']);
  assert.equal(await page.locator('[data-map-node=yiling] a').innerText(), '查看本章结局');
  await page.locator('[data-map-node=yiling] a').click();
  frame = page.frameLocator('iframe'); await frame.locator('.ending').waitFor();
  assert.equal(await frame.locator('[data-action=campaign-next]').count(), 0);
  await page.goto(base + '/?chapter=jingzhou'); await page.waitForURL(/locked=jingzhou/);
  checks.push('six real API rounds with mock AI preserve the result; completion and direct Jingzhou URL cannot unlock other chapters; map opens the saved ending');
  await advance('wuzhang'); await map(); await locked(['jieting', 'jingzhou', 'luofengpo']);
  await advance('grain'); await map(); await locked(['jingzhou', 'luofengpo']);
  assert.equal(await page.locator('[data-map-node=yiling] .map-early-access').count(), 1);
  await advance('jieting'); await map();
  assert.equal(await page.locator('[data-map-node=yiling] .map-early-access').count(), 0);
  assert.equal(await page.locator('[data-map-node=jingzhou] a').count(), 1);
  await locked(['luofengpo']);
  assert.equal(await page.evaluate(() => localStorage.getItem('yiling-rescue-campaign-session-v1')), session);
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('wzy:chapter-results:v1')).yiling), result);
  await page.locator('[data-map-node=yiling] a').click();
  frame = page.frameLocator('iframe'); await frame.locator('[data-action=campaign-next]').click();
  await page.waitForURL(/chapter=jingzhou/); await page.locator('#spoken-line').waitFor();
  checks.push('simulated sequential completion of chapters 1–3 removes the early label and opens Jingzhou using the same Yiling result');
  await page.goto(base + '/?chapter=yiling'); frame = page.frameLocator('iframe');
  await frame.locator('.ending [data-action=restart]').click();
  await frame.locator('#modal [data-action=new]').click();
  await frame.locator('.campaign-header').waitFor();
  await page.waitForFunction(old => localStorage.getItem('yiling-rescue-campaign-session-v1') !== old, session);
  await frame.locator('#scene-dialog').waitFor({ state: 'hidden' });
  await frame.locator('.campaign-header [data-action=campaign-map]').click(); await page.locator('.chapter-map').waitFor();
  assert.equal(await page.locator('[data-map-node=yiling] a').innerText(), '继续这一章');
  assert.equal(await page.evaluate(() => localStorage.getItem('yiling-rescue-campaign-session-v1:before-new')), session);
  checks.push('explicit chapter replay backs up the completed session and the map resumes the new round instead of labelling it as an ending');
  assert.deepEqual(errors, []);
  writeFileSync(resolve(out, 'verification.json'), JSON.stringify({ passed: true, checks, errors, mockAI: true }, null, 2));
  console.log(JSON.stringify({ passed: true, checks, errors }));
} finally { await browser.close(); server.closeAllConnections(); await new Promise(r => server.close(r)); }
