/** Opt-in live procurement + dialogue check. Uses an isolated browser, never reads credentials. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const output = resolve('outputs/supplies-20261024'); mkdirSync(output, { recursive: true });
const fixture = JSON.parse(readFileSync('GameStarter/web-demo/.build/playtest/weiyan-second.json', 'utf8'));
const key = 'wuzhang-chapter-session-v1', errors = [], checks = [];
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
try {
    const context = await browser.newContext({ viewport: { width: 1366, height: 768 }, reducedMotion: 'reduce' });
    await context.addInitScript(({ key, fixture }) => {
        if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(fixture));
        localStorage.setItem('wuzhang-reduced-motion', '1'); localStorage.setItem('wuzhang-voice-muted', '1');
    }, { key, fixture });
    const page = await context.newPage(); page.setDefaultTimeout(90000);
    page.on('pageerror', e => errors.push(e.message));
    const state = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
    await page.goto('http://127.0.0.1:8812/'); await page.locator('[data-action=continue]').click();
    const words = '不入丞相帐。姜维已答应帐外接报，我们现在立即交报并核回令。我想用一套纸笔当面记下姜维实际说的口令，念回去请他核对，之后照原流程传令。请找一套含纸和笔的完整记录套装。';
    await page.locator('#player-expression').fill(words);
    await page.locator('[data-action=supplies]').first().click();
    await page.locator('[data-phone-prompt=ask]').click();
    assert.equal(await page.locator('#shopping-query').inputValue(), '我想问问');
    await page.locator('#shopping-query').fill('我想问问，普通纸笔能直接证明诸葛亮已经死了吗？');
    await page.locator('[data-action=search-supplies]').click();
    await page.waitForFunction(() => !document.querySelector('[data-action=cancel-shopping]'));
    const answer = await page.locator('.phone-message.assistant').last().innerText();
    assert.match(answer, /不能|无法|不行|不足/); assert.deepEqual((await state()).supplies.purchases, []);
    checks.push('Live read-only assistant answers an ordinary question without purchasing or advancing the plot');
    await page.locator('[data-phone-prompt=buy]').click();
    assert.equal(await page.locator('#shopping-query').inputValue(), '帮我买');
    await page.locator('#shopping-query').fill('帮我买一套包含纸和中性笔的完整套装，仅一项商品，不要拆成多张卡。用途：' + words);
    const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/game/shop') && r.request().method() === 'POST');
    await page.locator('[data-action=search-supplies]').click();
    const response = await responsePromise, proposal = await response.json();
    assert.equal(response.status(), 200, JSON.stringify(proposal));
    const item = proposal.products.find(p => /中性笔|圆珠笔|铅笔|签字笔|纸笔|含笔/.test(p.name) && /纸|本/.test(p.name));
    assert.ok(item, 'The live model must suggest a complete paper and pen set');
    assert.ok(item.price > 0 && item.price <= 5000);
    assert.ok(item.id.startsWith('shop-'));
    await page.locator(`[data-buy-offer="${item.id}"]`).waitFor();
    assert.deepEqual((await state()).supplies.purchases, []);
    await page.screenshot({ path: resolve(output, 'dynamic-shopping-live.png') });
    await page.locator(`[data-buy-offer="${item.id}"]`).click();
    assert.deepEqual((await state()).supplies.custom, [item]);
    await page.locator(`[data-attach-item="${item.id}"]`).click();
    await page.locator('[data-action=close-modal]').click();
    await page.locator('[data-action=save]').click(); await page.locator('[data-store-slot="1"]').click();
    await page.locator('[data-action=close-modal]').click();
    await page.locator('[data-action=save]').click(); await page.locator('[data-load-slot="1"]').click();
    assert.deepEqual((await state()).supplies.custom, [item]);
    assert.deepEqual((await state()).supplies.attached, [item.id]);
    checks.push('Phone chat → live AI inference + search → dynamic item → explicit virtual purchase → save/load');
    await page.locator('#player-expression').fill('有这套纸笔就证明诸葛亮已经死了，立即撤军。');
    await page.locator('[data-action=speak]').click();
    await page.waitForFunction(key => ['ready', 'failed'].includes(JSON.parse(localStorage.getItem(key)).speech?.status), key);
    assert.equal((await state()).speech.status, 'ready', JSON.stringify((await state()).speech));
    assert.equal((await state()).speech.itemDecision.route, null);
    await page.locator('.game-scene').click({ position: { x: 24, y: 300 } });
    await page.locator('.game-scene').click({ position: { x: 24, y: 300 } });
    assert.equal((await state()).phase, 'expression');
    await page.locator('#player-expression').fill(words.replace('请找一套含纸和笔的完整记录套装。', '我已有这套纸笔，可以当面记录和复核。'));
    await page.locator('[data-action=speak]').click();
    await page.waitForFunction(key => ['ready', 'failed'].includes(JSON.parse(localStorage.getItem(key)).speech?.status), key);
    assert.equal((await state()).speech.status, 'ready', JSON.stringify((await state()).speech));
    assert.equal((await state()).speech.itemDecision.route, 'item-plan');
    assert.equal((await state()).supplies.agreement, null);
    await page.locator('.game-scene').click({ position: { x: 24, y: 300 } });
    for (let step = 0; step < 70 && (await state()).phase !== 'ending'; step++) {
        if (await page.locator('[data-story-film]').count()) {
            const confirm = page.locator('[data-film-confirm]');
            if (!await confirm.isVisible()) await page.locator('[data-cinema-action=skip]').click();
            if (await confirm.isVisible()) await confirm.click();
        } else if ((await state()).phase === 'cinematic') await page.locator('[data-cinema-action=skip]').click();
        else await page.locator('.game-scene').click({ position: { x: 24, y: 300 } });
    }
    assert.equal((await state()).end, 'item-plan'); assert.equal((await state()).story.flags.REPORT_CLOSED, true);
    checks.push('Live AI rejects fake death proof; accepts actual paper/pen record-and-verify plan; original handoff completes; item-plan ending');
    await page.screenshot({ path: resolve(output, 'dynamic-ending-live.png') });
    assert.deepEqual(errors, []);
    const report = { checks, errors, product: item, ending: (await state()).end };
    writeFileSync(resolve(output, 'dynamic-live-report.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify({ checks, errors, product: item.name, price: item.price, priceKind: item.priceKind, searchState: item.searchState }));
} finally { await browser.close(); }
