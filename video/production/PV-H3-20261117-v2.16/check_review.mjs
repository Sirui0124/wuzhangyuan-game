import {chromium} from 'playwright';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
const dir=path.join(process.cwd(),'video/production/PV-H3-20261117-v2.16');
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(path.join(dir,'成片审阅-v2.16.html')).href);
await page.waitForFunction(()=>document.querySelector('video').readyState>=1);
const v=page.locator('video');const metadata=await v.evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight}));
if(Math.abs(metadata.duration-75.833333)>.03||metadata.width!==1280||metadata.height!==720)throw Error(JSON.stringify(metadata));
await v.evaluate(v=>{v.muted=true;v.currentTime=69;v.playbackRate=1;return v.play()});
await page.waitForFunction(()=>document.querySelector('video').ended,null,{timeout:30000});
await page.screenshot({path:path.join(dir,'review-desktop.png')});
await page.setViewportSize({width:390,height:844});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);if(overflow||errors.length)throw Error(JSON.stringify({overflow,errors}));
for(const href of await page.locator('a[href]').evaluateAll(a=>a.map(x=>x.href)))if(href.startsWith('file:'))await fs.access(new URL(href));
await browser.close();
await fs.writeFile(path.join(dir,'browser-verification.json'),JSON.stringify({status:'pass',metadata,playback:'muted 1x 69s to end',mobileOverflow:overflow,localLinksExist:true,pageErrors:errors,note:'技术播放检查，不等于完整人工视听审阅'},null,2));
console.log('Tail playback and links passed');
