import {chromium} from 'playwright';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
const dir=path.join(process.cwd(),'video/production/PV-redesign-20261115-v2');
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(path.join(dir,'整体优化审阅.html')).href);
await page.waitForFunction(()=>document.querySelector('video').readyState>=1);
const v=page.locator('video');
const first=await v.evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,error:v.error?.message||null}));
if(first.duration!==92||first.width!==1280||first.height!==720||first.error)throw Error('Wrong main metadata');
const images=await page.locator('img').evaluateAll(a=>a.map(x=>({src:x.getAttribute('src'),ok:x.complete&&x.naturalWidth>0})));
if(images.some(x=>!x.ok))throw Error('Image missing');
await page.locator('.shot[data-time="59"]').click();
await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-59)<.1);
await page.locator('#raw').click();
await page.waitForFunction(()=>document.querySelector('video').readyState>=1&&document.querySelector('#raw').getAttribute('aria-pressed')==='true'&&Math.abs(document.querySelector('video').currentTime-59)<.1);
await page.locator('#clean').click();
await page.waitForFunction(()=>document.querySelector('video').readyState>=1&&document.querySelector('#clean').getAttribute('aria-pressed')==='true'&&Math.abs(document.querySelector('video').currentTime-59)<.1);
await page.evaluate(()=>scrollTo(0,0));await v.evaluate(v=>{v.currentTime=0;v.muted=true;v.playbackRate=1;return v.play()});
await page.waitForFunction(()=>document.querySelector('video').currentTime>1);
await page.screenshot({path:path.join(dir,'review-desktop.png')});
console.log(JSON.stringify({stage:'playing',metadata:first,images:images.length,seekAndAudioSwitch:'pass'}));
await page.waitForFunction(()=>document.querySelector('video').ended,null,{timeout:120000});
const playback=await v.evaluate(v=>({ended:v.ended,currentTime:v.currentTime,duration:v.duration,error:v.error?.message||null,quality:v.getVideoPlaybackQuality?.()}));
await page.setViewportSize({width:390,height:844});await page.evaluate(()=>scrollTo(0,0));
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);if(overflow)throw Error('Mobile overflow');
await page.screenshot({path:path.join(dir,'review-mobile.png')});
const links=await page.locator('a[href]').evaluateAll(a=>a.map(x=>x.href));
for(const link of links){if(link.startsWith('file:'))await fs.access(new URL(link));}
await browser.close();
if(errors.length||!playback.ended||playback.error)throw Error(JSON.stringify({errors,playback}));
await fs.writeFile(path.join(dir,'browser-verification.json'),JSON.stringify({date:'2026-11-15',status:'pass',metadata:first,playback,images,mobileOverflow:overflow,seekAndAudioSwitch:'pass',localLinksExist:true,pageErrors:errors,note:'Headless Chrome muted playback at1x to92s; technical verification only, not human visual/auditory approval.'},null,2));
console.log(JSON.stringify({stage:'complete',playback,mobileOverflow:overflow}));
